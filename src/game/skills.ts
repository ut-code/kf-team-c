export function abilitiesFromSkills(ids: string[]): Record<Ability, number> {
    const values = { IQ: 18, EQ: 16, SYSTEM: 12 };
    for (const skill of SKILLS)
        if (ids.includes(skill.id))
            values[skill.branch] = Math.min(100, values[skill.branch] + skill.gain);
    return values;
}
export function skillBlockReason(
    state: Pick<GameState, 'skills' | 'abilities'>,
    skill: Skill,
): string | null {
    if (state.skills.includes(skill.id)) return '習得済み';
    if (skill.excludes && state.skills.includes(skill.excludes)) return '排他的な路線を選択済み';
    const missing = skill.requires.filter((id) => !state.skills.includes(id));
    if (missing.length)
        return `前提：${missing.map((id) => SKILLS.find((s) => s.id === id)!.name).join('・')}`;
    for (const [ability, value] of Object.entries(skill.abilityRequirements ?? {}))
        if (state.abilities[ability as Ability] < value) return `${ability} ${value}以上が必要`;
    return null;
}
